export const LOADING_WORD_INTERVAL_MS = 10_000;
export const LOADING_DOT_INTERVAL_MS = 650;

export function shuffleLoadingWords(
  random: () => number = Math.random,
  previousWord?: string,
): string[] {
  const words = [...LOADING_WORDS];
  for (let index = words.length - 1; index > 0; index--) {
    const swapIndex = Math.min(index, Math.floor(random() * (index + 1)));
    [words[index], words[swapIndex]] = [words[swapIndex]!, words[index]!];
  }

  if (words.length > 1 && words[0] === previousWord) {
    const swapIndex = 1 + Math.floor(random() * (words.length - 1));
    [words[0], words[swapIndex]] = [words[swapIndex]!, words[0]!];
  }
  return words;
}
