export function shuffleLoadingPhrases(
  random: () => number = Math.random,
  previousPhrase?: string,
): string[] {
  const phrases = [...LOADING_PHRASES];
  for (let index = phrases.length - 1; index > 0; index--) {
    const swapIndex = Math.min(index, Math.floor(random() * (index + 1)));
    [phrases[index], phrases[swapIndex]] = [
      phrases[swapIndex]!,
      phrases[index]!,
    ];
  }

  if (phrases.length > 1 && phrases[0] === previousPhrase) {
    const swapIndex = 1 + Math.floor(random() * (phrases.length - 1));
    [phrases[0], phrases[swapIndex]] = [phrases[swapIndex]!, phrases[0]!];
  }
  return phrases;
}
